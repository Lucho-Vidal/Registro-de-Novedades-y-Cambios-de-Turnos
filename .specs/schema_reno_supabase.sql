-- Esquema PostgreSQL para Supabase - Proyecto RENO v2.0.0
-- Tablas prefijadas reno_* para convivir en el mismo proyecto con CRONO-PCT

CREATE TABLE IF NOT EXISTS reno_dotaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_tipos_novedad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    dias INTEGER NOT NULL DEFAULT 0,
    exportar_descubierto BOOLEAN NOT NULL DEFAULT true,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_personal_estacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    dotacion TEXT,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_destinatarios_informe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_destinatarios_ordenamiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_empleados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legajo INTEGER NOT NULL UNIQUE,
    apellidos_nombres TEXT NOT NULL DEFAULT '',
    especialidad TEXT NOT NULL DEFAULT '',
    dotacion TEXT NOT NULL DEFAULT '',
    turnos TEXT NOT NULL DEFAULT '',
    franco TEXT NOT NULL DEFAULT '',
    franco_horario TEXT NOT NULL DEFAULT '',
    jornada_horas INTEGER NOT NULL DEFAULT 6 CHECK (jornada_horas IN (6, 7)),
    activo BOOLEAN NOT NULL DEFAULT true,
    actualizado_en TIMESTAMPTZ DEFAULT now(),
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_permisos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_rol_permisos (
    rol_id BIGINT NOT NULL REFERENCES reno_roles(id) ON DELETE CASCADE,
    permiso_id BIGINT NOT NULL REFERENCES reno_permisos(id) ON DELETE CASCADE,
    PRIMARY KEY (rol_id, permiso_id)
);

CREATE TABLE IF NOT EXISTS reno_usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    nombre TEXT NOT NULL DEFAULT '',
    legajo INTEGER,
    password_hash TEXT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT true,
    creado_en TIMESTAMPTZ DEFAULT now(),
    ultimo_ingreso TIMESTAMPTZ,
    password_cambiado_en TIMESTAMPTZ,
    debe_cambiar_clave BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_usuario_roles (
    usuario_id BIGINT NOT NULL REFERENCES reno_usuarios(id) ON DELETE CASCADE,
    rol_id BIGINT NOT NULL REFERENCES reno_roles(id) ON DELETE CASCADE,
    PRIMARY KEY (usuario_id, rol_id)
);

CREATE TABLE IF NOT EXISTS reno_novedades (
    id BIGINT PRIMARY KEY,
    registrado_en TIMESTAMPTZ NOT NULL,
    legajo INTEGER NOT NULL,
    apellidos_nombres TEXT NOT NULL DEFAULT '',
    especialidad TEXT NOT NULL DEFAULT '',
    dotacion TEXT NOT NULL DEFAULT '',
    turnos TEXT NOT NULL DEFAULT '',
    franco TEXT NOT NULL DEFAULT '',
    novedad TEXT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    referencia_estacion TEXT NOT NULL,
    supervisor TEXT NOT NULL,
    observaciones TEXT,
    usuario_windows TEXT,
    usuario_id BIGINT REFERENCES reno_usuarios(id),
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_novedad_reemplazos (
    id BIGINT PRIMARY KEY,
    novedad_id BIGINT NOT NULL REFERENCES reno_novedades(id) ON DELETE CASCADE,
    legajo_reemplazo INTEGER NOT NULL,
    apellidos_nombres_reemplazo TEXT NOT NULL DEFAULT '',
    turnos_reemplazo TEXT NOT NULL DEFAULT '',
    franco_reemplazo TEXT NOT NULL DEFAULT '',
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    usuario_windows TEXT,
    usuario_id BIGINT REFERENCES reno_usuarios(id),
    creado_en TIMESTAMPTZ DEFAULT now(),
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_cambios_turno (
    id BIGINT PRIMARY KEY,
    registrado_en TIMESTAMPTZ NOT NULL,
    legajo_1 INTEGER NOT NULL,
    apellidos_nombres_1 TEXT NOT NULL DEFAULT '',
    especialidad_1 TEXT NOT NULL DEFAULT '',
    dotacion_1 TEXT NOT NULL DEFAULT '',
    turnos_1 TEXT NOT NULL DEFAULT '',
    franco_1 TEXT NOT NULL DEFAULT '',
    legajo_2 INTEGER NOT NULL,
    apellidos_nombres_2 TEXT NOT NULL DEFAULT '',
    especialidad_2 TEXT NOT NULL DEFAULT '',
    dotacion_2 TEXT NOT NULL DEFAULT '',
    turnos_2 TEXT NOT NULL DEFAULT '',
    franco_2 TEXT NOT NULL DEFAULT '',
    fecha_cambio DATE NOT NULL,
    referencia_estacion TEXT NOT NULL,
    supervisor TEXT NOT NULL,
    observaciones TEXT,
    usuario_windows TEXT,
    usuario_id BIGINT REFERENCES reno_usuarios(id),
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_ciclo_jornadas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legajo INTEGER NOT NULL,
    fecha DATE NOT NULL,
    toma TEXT,
    deja TEXT,
    franco_anticipado BOOLEAN NOT NULL DEFAULT false,
    observaciones TEXT,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    usuario_windows TEXT,
    usuario_id BIGINT REFERENCES reno_usuarios(id),
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE(legajo, fecha)
);

CREATE TABLE IF NOT EXISTS reno_configuracion (
    clave TEXT PRIMARY KEY,
    valor TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reno_auditoria (
    id BIGINT PRIMARY KEY,
    usuario_id BIGINT REFERENCES reno_usuarios(id),
    usuario_windows TEXT,
    accion TEXT NOT NULL,
    entidad TEXT NOT NULL,
    entidad_id BIGINT,
    datos_anteriores JSONB,
    datos_nuevos JSONB,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

