-- Características clave de este esquema:
-- - Prefijo 'reno_*': Permite convivir en el mismo proyecto con CRONO-PCT u otras aplicaciones.
-- - Idempotente: Se puede ejecutar múltiples veces sin borrar ni duplicar datos existentes.
-- - Permisos y RLS Universales: Todos los usuarios con diferentes roles (Operadores,
--   Supervisores, Jefatura, Administradores) pueden subir, sincronizar, editar y consultar cambios.
