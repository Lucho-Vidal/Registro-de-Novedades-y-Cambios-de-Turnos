-- 1. FUNCIÓN AUTOMÁTICA PARA ACTUALIZAR COLUMNA updated_at
CREATE OR REPLACE FUNCTION reno_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


